def start(title,subtitle=''):
    global page,y
    page+=1; c.setFillColor(GRAY); c.rect(0,H-42,W,42,fill=1,stroke=0)
    c.setFont('ArialBold',9); c.setFillColor(BLUE); c.drawString(M,H-26,'Наземная станция')
    c.setFillColor(MUTED); c.setFont('Arial',9); c.drawRightString(W-M,H-26,'Практическое занятие 3 / Вариант 2')
    y=H-76; para(title,head)
    if subtitle: para(subtitle,small)
    y-=10

def para(text,style=body):
    global y
    p=Paragraph(text,style); _,h=p.wrap(CW,700); p.drawOn(c,M,y-h); y-=h+style.spaceAfter

def section(text):
    global y
    y-=8; para(text,sub)

def image_file(name,width=CW):
    global y
    path=V/name
    with Image.open(path) as im: iw,ih=im.size
    height=width*ih/iw
    c.drawImage(ImageReader(str(path)),M+(CW-width)/2,y-height,width,height,mask='auto'); y-=height+12

def table(rows,widths):
    global y
    data=[[Paragraph(str(v),cell) for v in row] for row in rows]
    t=Table(data,colWidths=widths,hAlign='LEFT')
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),colors.HexColor('#EDF0FF')),('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),8),('RIGHTPADDING',(0,0),(-1,-1),8),('TOPPADDING',(0,0),(-1,-1),9),('BOTTOMPADDING',(0,0),(-1,-1),9),('LINEBELOW',(0,0),(-1,-1),.4,colors.HexColor('#E5EAF3')),('ROWBACKGROUNDS',(0,1),(-1,-1),[colors.white,colors.HexColor('#FAFBFE')])]))
    _,h=t.wrap(CW,700); t.drawOn(c,M,y-h); y-=h+12

def finish():
    assert y>43, f'Page {page} overflow: {y}'
